import re
from datetime import datetime

print("\n" + "="*80)
print("STEP 7: CREATE PRE/POST MIGRATION VALIDATION QUERIES")
print("="*80)

# Extract all V3 IDs from the final migration file
print("\n[1/3] Extracting restaurant IDs from migration file...")

with open('extracted_data/FINAL_DELIVERY_AREAS_MIGRATION.sql', 'r', encoding='utf-8') as f:
    migration_sql = f.read()

v3_id_matches = re.findall(r'VALUES\s*\((\d+),', migration_sql)
v3_ids = sorted(list(set([int(id) for id in v3_id_matches])))

print(f"   Extracted {len(v3_ids)} unique restaurant IDs")

# Generate V3 ID list for SQL queries
v3_ids_sql = ', '.join(map(str, v3_ids))

# Create pre-migration checks
print("\n[2/3] Creating pre-migration checks...")

with open('extracted_data/pre_migration_checks.sql', 'w', encoding='utf-8') as f:
    f.write("-- ============================================================================\n")
    f.write("-- PRE-MIGRATION VALIDATION CHECKS\n")
    f.write(f"-- Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    f.write("-- ============================================================================\n")
    f.write("-- Run these checks BEFORE executing the migration to ensure the database\n")
    f.write("-- is in the correct state.\n")
    f.write("-- ============================================================================\n\n")
    
    f.write("-- CHECK 1: Current delivery area count\n")
    f.write("SELECT \n")
    f.write("  'Current Areas' as check_name,\n")
    f.write("  COUNT(*) as count\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas;\n\n")
    
    f.write("-- CHECK 2: Verify all target restaurants exist in V3\n")
    f.write("SELECT \n")
    f.write("  'Missing Restaurants' as check_name,\n")
    f.write("  COUNT(*) as count\n")
    f.write("FROM (\n")
    f.write(f"  VALUES ({'), ('.join([f'{id}' for id in v3_ids])})\n")
    f.write(") AS migration_restos(restaurant_id)\n")
    f.write("WHERE restaurant_id NOT IN (\n")
    f.write("  SELECT id FROM menuca_v3.restaurants\n")
    f.write(");\n")
    f.write("-- Expected: 0 (all restaurants should exist)\n\n")
    
    f.write("-- CHECK 3: Check if any target restaurants already have areas\n")
    f.write("SELECT \n")
    f.write("  'Restaurants with Existing Areas' as check_name,\n")
    f.write("  COUNT(DISTINCT r.id) as count\n")
    f.write("FROM menuca_v3.restaurants r\n")
    f.write("INNER JOIN menuca_v3.restaurant_delivery_areas da ON da.restaurant_id = r.id\n")
    f.write(f"WHERE r.id IN ({v3_ids_sql});\n")
    f.write("-- Note: MVP restaurants (5) already have areas from Phase 1\n")
    f.write("-- Expected: 5 (only MVP restaurants)\n\n")
    
    f.write("-- CHECK 4: Verify PostGIS extension is enabled\n")
    f.write("SELECT \n")
    f.write("  'PostGIS Enabled' as check_name,\n")
    f.write("  CASE WHEN COUNT(*) > 0 THEN 'YES' ELSE 'NO' END as status\n")
    f.write("FROM pg_extension \n")
    f.write("WHERE extname = 'postgis';\n")
    f.write("-- Expected: YES\n\n")
    
    f.write("-- CHECK 5: List restaurants to be migrated\n")
    f.write("SELECT \n")
    f.write("  r.id as v3_id,\n")
    f.write("  r.name,\n")
    f.write("  r.legacy_v2_id,\n")
    f.write("  r.legacy_v1_id,\n")
    f.write("  COUNT(da.id) as existing_areas\n")
    f.write("FROM menuca_v3.restaurants r\n")
    f.write("LEFT JOIN menuca_v3.restaurant_delivery_areas da ON da.restaurant_id = r.id\n")
    f.write(f"WHERE r.id IN ({v3_ids_sql})\n")
    f.write("GROUP BY r.id, r.name, r.legacy_v2_id, r.legacy_v1_id\n")
    f.write("ORDER BY r.id;\n\n")
    
    f.write("-- ============================================================================\n")
    f.write("-- VALIDATION GATE\n")
    f.write("-- ============================================================================\n")
    f.write("-- Before proceeding:\n")
    f.write("--   - CHECK 2 should return 0 (no missing restaurants)\n")
    f.write("--   - CHECK 4 should return YES (PostGIS enabled)\n")
    f.write("--   - Review CHECK 5 to confirm restaurant list\n")
    f.write("-- ============================================================================\n")

print(f"   Pre-migration checks saved: extracted_data/pre_migration_checks.sql")

# Create post-migration checks
print("\n[3/3] Creating post-migration checks...")

with open('extracted_data/post_migration_checks.sql', 'w', encoding='utf-8') as f:
    f.write("-- ============================================================================\n")
    f.write("-- POST-MIGRATION VALIDATION CHECKS\n")
    f.write(f"-- Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    f.write("-- ============================================================================\n")
    f.write("-- Run these checks AFTER executing the migration to ensure data integrity.\n")
    f.write("-- ============================================================================\n\n")
    
    f.write("-- CHECK 1: All restaurants have delivery areas\n")
    f.write("SELECT \n")
    f.write("  'Restaurants with Areas' as check_name,\n")
    f.write("  COUNT(DISTINCT restaurant_id) as count,\n")
    f.write(f"  {len(v3_ids)} as expected\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas\n")
    f.write(f"WHERE restaurant_id IN ({v3_ids_sql});\n")
    f.write(f"-- Expected: {len(v3_ids)}\n\n")
    
    f.write("-- CHECK 2: Total areas inserted\n")
    f.write("SELECT \n")
    f.write("  'Total Areas Inserted' as check_name,\n")
    f.write("  COUNT(*) as count,\n")
    f.write("  91 as expected\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas\n")
    f.write(f"WHERE restaurant_id IN ({v3_ids_sql});\n")
    f.write("-- Expected: 91 (88 from V2 + 3 from V1)\n\n")
    
    f.write("-- CHECK 3: Verify all geometries are valid\n")
    f.write("SELECT \n")
    f.write("  'Invalid Geometries' as check_name,\n")
    f.write("  COUNT(*) as count\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas\n")
    f.write(f"WHERE restaurant_id IN ({v3_ids_sql})\n")
    f.write("AND NOT ST_IsValid(geometry);\n")
    f.write("-- Expected: 0\n\n")
    
    f.write("-- CHECK 4: Verify area numbering is sequential per restaurant\n")
    f.write("WITH area_numbers AS (\n")
    f.write("  SELECT \n")
    f.write("    restaurant_id,\n")
    f.write("    array_agg(area_number ORDER BY area_number) as numbers,\n")
    f.write("    MAX(area_number) as max_num\n")
    f.write("  FROM menuca_v3.restaurant_delivery_areas\n")
    f.write(f"  WHERE restaurant_id IN ({v3_ids_sql})\n")
    f.write("  GROUP BY restaurant_id\n")
    f.write(")\n")
    f.write("SELECT \n")
    f.write("  'Sequential Numbering Errors' as check_name,\n")
    f.write("  COUNT(*) as count\n")
    f.write("FROM area_numbers\n")
    f.write("WHERE array_length(numbers, 1) != max_num;\n")
    f.write("-- Expected: 0\n\n")
    
    f.write("-- CHECK 5: Detailed per-restaurant summary\n")
    f.write("SELECT \n")
    f.write("  r.id as v3_id,\n")
    f.write("  r.name,\n")
    f.write("  r.legacy_v2_id,\n")
    f.write("  r.legacy_v1_id,\n")
    f.write("  COUNT(da.id) as areas_count,\n")
    f.write("  STRING_AGG(da.area_number::text, ',' ORDER BY da.area_number) as area_numbers,\n")
    f.write("  MIN(ST_NPoints(da.geometry)) as min_points,\n")
    f.write("  MAX(ST_NPoints(da.geometry)) as max_points,\n")
    f.write("  BOOL_AND(ST_IsValid(da.geometry)) as all_valid\n")
    f.write("FROM menuca_v3.restaurants r\n")
    f.write("LEFT JOIN menuca_v3.restaurant_delivery_areas da ON da.restaurant_id = r.id\n")
    f.write(f"WHERE r.id IN ({v3_ids_sql})\n")
    f.write("GROUP BY r.id, r.name, r.legacy_v2_id, r.legacy_v1_id\n")
    f.write("ORDER BY areas_count DESC, r.name;\n\n")
    
    f.write("-- CHECK 6: Summary statistics\n")
    f.write("SELECT \n")
    f.write("  COUNT(DISTINCT restaurant_id) as restaurants_migrated,\n")
    f.write("  COUNT(*) as total_areas,\n")
    f.write("  ROUND(AVG(ST_NPoints(geometry)), 2) as avg_points_per_polygon,\n")
    f.write("  MIN(ST_NPoints(geometry)) as min_points,\n")
    f.write("  MAX(ST_NPoints(geometry)) as max_points,\n")
    f.write("  ROUND(AVG(ST_Area(geometry::geography)), 2) as avg_area_sq_meters\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas\n")
    f.write(f"WHERE restaurant_id IN ({v3_ids_sql});\n\n")
    
    f.write("-- CHECK 7: Test spatial queries (sample point)\n")
    f.write("-- This tests if spatial indexing is working correctly\n")
    f.write("SELECT \n")
    f.write("  'Sample Spatial Query Test' as check_name,\n")
    f.write("  restaurant_id,\n")
    f.write("  area_name,\n")
    f.write("  ST_Contains(\n")
    f.write("    geometry, \n")
    f.write("    ST_SetSRID(ST_MakePoint(-75.7077, 45.3975), 4326)\n")
    f.write("  ) as contains_test_point\n")
    f.write("FROM menuca_v3.restaurant_delivery_areas\n")
    f.write("WHERE restaurant_id = 13\n")
    f.write("LIMIT 1;\n\n")
    
    f.write("-- ============================================================================\n")
    f.write("-- VALIDATION SUMMARY\n")
    f.write("-- ============================================================================\n")
    f.write("-- All checks should pass:\n")
    f.write(f"--   - CHECK 1: {len(v3_ids)} restaurants with areas\n")
    f.write("--   - CHECK 2: 91 total areas\n")
    f.write("--   - CHECK 3: 0 invalid geometries\n")
    f.write("--   - CHECK 4: 0 sequential numbering errors\n")
    f.write("--   - CHECK 5: All restaurants listed with area counts\n")
    f.write("--   - CHECK 6: Statistics look reasonable\n")
    f.write("--   - CHECK 7: Spatial query works\n")
    f.write("-- ============================================================================\n")

print(f"   Post-migration checks saved: extracted_data/post_migration_checks.sql")

print("\n" + "="*80)
print("[COMPLETE] STEP 7 COMPLETE - Validation queries created")
print("="*80)
print("\nNext steps:")
print("  1. Review: extracted_data/FINAL_DELIVERY_AREAS_MIGRATION.sql")
print("  2. Run: extracted_data/pre_migration_checks.sql")
print("  3. Execute: extracted_data/FINAL_DELIVERY_AREAS_MIGRATION.sql")
print("  4. Run: extracted_data/post_migration_checks.sql")
print("="*80 + "\n")




